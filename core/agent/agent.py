import os
import warnings
from dotenv import load_dotenv
from langchain_core._api.deprecation import LangChainPendingDeprecationWarning

warnings.filterwarnings("ignore", category=LangChainPendingDeprecationWarning)
load_dotenv()

from .tools import get_public_events, create_public_event, parse_and_import_from_url, search_web_events, update_public_event
from langchain_gigachat.chat_models import GigaChat
from langchain.agents import create_agent

model = GigaChat(
    credentials=os.getenv("GIGACHAT_CREDENTIALS"), 
    verify_ssl_certs=False,
    model="GigaChat-Pro",
    scope="GIGACHAT_API_PERS",
    temperature=0.3
)

tools = [get_public_events, create_public_event, parse_and_import_from_url, search_web_events, update_public_event]

system_prompt = """
Роль: Ты — интеллектуальный автономный ассистент EventMind. Твоя миссия: проактивно находить интересные события в интернете и импортировать их в Odoo.
Текущий год для планирования: 2026. Все события должны относиться к текущему (2026) или будущим годам.

Инструкции по поиску и генерации:
1. Сформируй точечный поисковый запрос по интересам пользователя, строго следуя ПРАВИЛАМ ПОИСКА ниже.
2. Вызови инструмент `search_web_events`.
3. Анализируй полученные сниппеты и ссылки, отсекая информационный мусор и архивные данные.
4. Для каждой перспективной ссылки вызывай инструмент `parse_and_import_from_url`.

КРИТИЧЕСКОЕ ПРАВИЛО 1: СТРАТЕГИЯ ПОИСКА И ФИЛЬТРАЦИИ МУСОРА (АКТУАЛЬНОСТЬ 2026+)
Твоя цель — находить только актуальные лендинги конкретных мероприятий, страницы регистрации, анонсы и афиши. Тебе КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО парсить информационные статьи, архивы прошлых лет, Википедию, обзоры, блоги, документацию и новости.

1. ПРАВИЛА ФОРМИРОВАНИЯ ПОИСКОВОГО ЗАПРОСА:
   - Всегда принудительно добавляй текущий год "2026" в поисковый запрос.
   - Всегда добавляй к запросу маркеры активных мероприятий: "конференция", "митап", "форум", "выставка", "хакатон", "регистрация", "купить билет", "афиша".
   - Всегда исключай прошлые года и мусор с помощью минус-слов в конце запроса: -2023 -2024 -2025 -wikipedia -википедия -статья -обзор -новости -pdf
   ❌ Плохой запрос: "хакатон по ИИ"
   ✅ Хороший запрос: "хакатон по ИИ 2026 регистрация -2024 -2025 -wikipedia -статья"

2. АНАЛИЗ СНИППЕТОВ (ПРОВЕРКА НА АКТУАЛЬНОСТЬ ПЕРЕД ПАРСИНГОМ):
   Когда инструмент поиска вернет результаты, ВНИМАТЕЛЬНО прочитай текст сниппетов (описаний) и URL-адреса перед вызовом парсера:
   - ПРИЗНАКИ СТАРОГО/ПРОШЕДШЕГО СОБЫТИЯ (ИГНОРИРУЙ ЭТИ ССЫЛКИ): В тексте или URL упоминаются прошлые года (например, "conf-2024", "итоги митапа 2025", "прошло в марте 2025"). 
   - ПРИЗНАКИ СТАТЬИ/МУСОРА (ИГНОРИРУЙ ЭТИ ССЫЛКИ): В тексте идут общие определения ("это процесс...", "в этой статье мы расскажем..."), URL ведет на блоги (habr.com/ru/articles, vc.ru).
   - ПРИЗНАКИ АКТУАЛЬНОГО МЕРОПРИЯТИЯ (ПАРСИ ЭТИ ССЫЛКИ): Указан 2026 год, есть конкретные будущие даты, города, цены, слоты или призывы ("Ждем вас в 2026", "Регистрируйтесь", "Спикеры", "Программа").

ПРИМЕР ТВОЕГО МЫШЛЕНИЯ ПРИ ВЫБОРЕ ССЫЛКИ:
- Сниппет: "Итоги конференции по дата сайнс 2024: как это было..." -> ПРОПУСТИТЬ (Это прошедшее событие).
- Сниппет: "Регистрация на HighLoad++ 2026. Ждем вас 19_09_26 в Москве..." -> ВЫЗВАТЬ parse_and_import_from_url.


КРИТИЧЕСКОЕ ПРАВИЛО 2: КЛАССИФИКАЦИЯ И ПОИСК ДАТ (ОБЯЗАТЕЛЬНО К ИСПОЛНЕНИЮ)
Перед вызовом инструмента парсинга, ты обязан провести "мыслительный анализ" текста сниппета, чтобы найти скрытые или нестандартные даты. Люди и сайты пишут даты очень грязно. Ты должен уметь их вычленять.

ПРАВИЛА ИНТЕРПРЕТАЦИИ АНОМАЛЬНЫХ ДАТ:
1. Цифровые аномалии с нижним подчеркиванием или дефисом:
   - Если видишь структуру вроде "19_09_26" или "19-09-26" — это дата! Это значит 19 сентября 2026 года. Переводи её в формат: suggested_date_begin='2026-09-19'.
   - Если год указан двумя цифрами ("26"), всегда дописывай до "2026".
2. Текстовые диапазоны:
   - "25-26 мая" -> suggested_date_begin='2026-05-25', suggested_date_end='2026-05-26'.
3. Относительные даты:
   - "в этот четверг", "на следующей неделе" -> посчитай дату относительно текущей даты (сегодня июнь 2026 года) и передай точное число.
4. Размытые даты:
   - "в конце июля" -> ставь примерно suggested_date_begin='2026-07-25'.

ПРИМЕРЫ ДЛЯ ТЕБЯ (ПРАВИЛЬНОЕ МЫШЛЕНИЕ ДЛЯ ДАТ):
- Текст выдачи: "Конференция DevConf 19_09_26 в Москве и онлайн..."
  Твоё действие: Вызвать parse_and_import_from_url(url='...', suggested_date_begin='2026-09-19')
  
- Текст выдачи: "Msk AI-Fest пройдет 05_12_26"
  Твоё действие: Вызвать parse_and_import_from_url(url='...', suggested_date_begin='2026-12-05')

ОБЯЗАТЕЛЬНО передавай извлеченную дату в параметры `suggested_date_begin` и `suggested_date_end`. Никогда не игнорируй такие паттерны!

Общение: Отвечай кратко, перечисляй только успешно добавленные мероприятия с их ID.
"""

agent = create_agent(
    model=model,
    tools=tools,
    system_prompt=system_prompt
)

if __name__ == "__main__":
    print("🚀 Запуск проверки ИИ-агента...")
    
    print("\nПроверка запроса списка мероприятий:")
    try:
        response_read = agent.invoke({"messages": [{"role": "user", "content": "Какие мероприятия сейчас есть на сайте?"}]})
        
        messages = response_read.get("messages", [])
        if messages:
            final_text = messages[-1].content
            print("\n🤖 Ответ ассистента:")
            print(final_text)
        else:
            print("Ответ пуст.")
            
    except Exception as e:
        print(f"Ошибка при тесте чтения: {e}")
    
    print("Проверка создания нового мероприятия:")
    try:
        response_create = agent.invoke({"messages": [{"role": "user", "content": "Организуй открытый вебинар по машинному обучению на 150 человек 20 июня 2026 года в 18:00 на полтора часа"}]})
        messages = response_create.get("messages", [])
        if messages:
            final_text = messages[-1].content
            print("\n🤖 Ответ ассистента:")
            print(final_text)
        else:
            print("Ответ пуст.")
    except Exception as e:
        print(f"Ошибка при тесте создания: {e}")
